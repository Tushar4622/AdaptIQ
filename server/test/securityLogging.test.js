const test = require('node:test');
const assert = require('node:assert/strict');
const requestId = require('../middleware/requestId');
const { auditAdminActions, auditDeniedRequests } = require('../middleware/securityAudit');
const { logSecurityEvent } = require('../services/securityLogger');

test('request IDs are generated by the server and returned in the response header', () => {
  const req = { headers: { 'x-request-id': 'client-controlled-value' } };
  const headers = {};
  const res = { setHeader: (name, value) => { headers[name] = value; } };
  let nextCalled = false;

  requestId(req, res, () => { nextCalled = true; });

  assert.match(req.requestId, /^[0-9a-f-]{36}$/i);
  assert.equal(headers['X-Request-ID'], req.requestId);
  assert.notEqual(req.requestId, req.headers['x-request-id']);
  assert.equal(nextCalled, true);
});

test('security events omit credentials, identifiers, request data, and arbitrary fields', () => {
  const originalWarn = console.warn;
  let output;
  console.warn = (line) => { output = line; };

  try {
    logSecurityEvent('request.denied', {
      requestId: 'request-123',
      method: 'PUT',
      baseUrl: '/api/admin',
      route: { path: '/users/:id/role' },
      body: { password: 'should-not-be-logged' },
      user: { email: 'person@example.com', _id: 'private-id' },
    }, {
      statusCode: 403,
      role: 'teacher',
      reason: 'insufficient_role',
      token: 'should-not-be-logged',
      targetId: 'private-id',
    });
  } finally {
    console.warn = originalWarn;
  }

  const event = JSON.parse(output);
  assert.equal(event.event, 'request.denied');
  assert.equal(event.requestId, 'request-123');
  assert.equal(event.route, '/api/admin/users/:id/role');
  assert.equal(event.statusCode, 403);
  assert.equal(event.role, 'teacher');
  assert.equal(JSON.stringify(event).includes('should-not-be-logged'), false);
  assert.equal(JSON.stringify(event).includes('person@example.com'), false);
  assert.equal(JSON.stringify(event).includes('private-id'), false);
});

test('authorization denials and admin mutations produce structured audit events', () => {
  const originalWarn = console.warn;
  const originalInfo = console.info;
  const entries = [];
  console.warn = (line) => entries.push(JSON.parse(line));
  console.info = (line) => entries.push(JSON.parse(line));

  const deniedReq = {
    requestId: 'deny-request',
    method: 'GET',
    baseUrl: '/api/courses',
    route: { path: '/:id' },
  };
  const deniedRes = {
    statusCode: 403,
    once(event, callback) {
      assert.equal(event, 'finish');
      this.onFinish = callback;
    },
  };
  const adminReq = {
    requestId: 'admin-request',
    method: 'PATCH',
    baseUrl: '/api/admin',
    user: { role: 'admin', _id: 'private-admin-id' },
    body: { email: 'private@example.com' },
  };
  const adminRes = {
    statusCode: 200,
    once(event, callback) {
      assert.equal(event, 'finish');
      this.onFinish = callback;
    },
  };

  try {
    auditDeniedRequests(deniedReq, deniedRes, () => {});
    deniedRes.onFinish();
    auditAdminActions(adminReq, adminRes, () => {});
    adminReq.route = { path: '/users/:id/role' };
    adminRes.onFinish();
  } finally {
    console.warn = originalWarn;
    console.info = originalInfo;
  }

  assert.equal(entries.length, 2);
  assert.equal(entries[0].event, 'request.denied');
  assert.equal(entries[0].statusCode, 403);
  assert.equal(entries[1].event, 'admin.action');
  assert.equal(entries[1].route, '/api/admin/users/:id/role');
  assert.equal(entries[1].role, 'admin');
  assert.equal(JSON.stringify(entries).includes('private-admin-id'), false);
  assert.equal(JSON.stringify(entries).includes('private@example.com'), false);
});
